const TranslationContext = createContext();

const SUPPORTED_LANGS = ["en", "fr"];

export function TranslationProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const stored = localStorage.getItem("fleetmark_lang");
    return SUPPORTED_LANGS.includes(stored) ? stored : "en";
  });

  useEffect(() => {
    localStorage.setItem("fleetmark_lang", lang);
    document.documentElement.setAttribute("data-lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => translations[lang]?.[key] || translations.en[key] || key;

  return (
    <TranslationContext.Provider value={{ lang, setLang, t }}>
      {children}
    </TranslationContext.Provider>
  );
}

// For code outside React (services/api.js): uses the saved language.
// eslint-disable-next-line react-refresh/only-export-components
export function translate(key) {
  const lang = localStorage.getItem("fleetmark_lang");
  return translations[lang]?.[key] || translations.en[key] || key;
}

// eslint-disable-next-line react-refresh/only-export-components
export function useTranslation() {
  const context = useContext(TranslationContext);
  if (!context) {
    throw new Error("useTranslation must be used within a TranslationProvider");
  }
  return context;
}
